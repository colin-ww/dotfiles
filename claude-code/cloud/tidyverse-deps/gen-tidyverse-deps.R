#!/usr/bin/env Rscript
# Maps the tidyverse's dependency structure -> tidyverse-deps.yml
#
# Run from the repo root (needs tidyverse installed; uses the installed versions):
#   Rscript claude-code/cloud/tidyverse-deps/gen-tidyverse-deps.R [out.yml]
#
# "dep" = Depends + Imports + LinkingTo, i.e. what install.packages() pulls in.
# Base and recommended packages (MASS, Matrix, mgcv, ...) are left out: they
# ship with r-base.

suppressPackageStartupMessages(library(tidyverse))

out <- coalesce(commandArgs(TRUE)[1], "claude-code/cloud/tidyverse-deps/tidyverse-deps.yml")
db <- installed.packages()
shipped_with_r <- rownames(db)[db[, "Priority"] %in% c("base", "recommended")]
sorted <- \(x) sort(unique(x), method = "radix")

deps <- \(pkgs, recursive) {
  tools::package_dependencies(pkgs, db = db, which = c("Depends", "Imports", "LinkingTo"), recursive = recursive) |>
    map(\(d) sorted(setdiff(d, shipped_with_r)))
}

# the tidyverse ----------------------------------------------------------------
core <- sorted(tidyverse:::core)
members <- sorted(tidyverse_packages(include_self = FALSE)) # what library(tidyverse) installs on purpose

tv <- tibble(pkg = members, core = pkg %in% core, direct = deps(pkg, FALSE), recursive = deps(pkg, TRUE)) |>
  mutate(
    beyond_dplyr = map(recursive, \(r) sorted(setdiff(r, c("dplyr", recursive[[match("dplyr", pkg)]])))),
    uses_members = map(direct, \(d) sorted(intersect(d, members))),
    uses_core    = map(direct, \(d) sorted(intersect(d, .env$core)))
  )

all_deps <- deps("tidyverse", TRUE)[[1]]

# YAML writer: lists get a "# n = <count>" comment, wrapped as flow sequences --
flow <- \(x, key, indent, width = 88) {
  items <- paste0(x, c(rep(",", max(length(x) - 1, 0)), ""))
  head <- strrep(" ", indent) |> paste0(key, ":")
  one <- paste0(head, " [", paste(items, collapse = " "), "]")
  if (nchar(one) <= width) return(paste0(one, "  # n = ", length(x)))
  wrapped <- strwrap(paste(items, collapse = " "), width = width - indent - 2)
  body <- paste0(strrep(" ", indent + 2), c("[", rep(" ", length(wrapped) - 1)), wrapped)
  c(paste0(head, "  # n = ", length(x)), body[-length(body)], paste0(body[length(body)], "]"))
}
edges <- \(d, key, indent) c(paste0(strrep(" ", indent), key, ":  # ", sum(lengths(d)), " edges"),
                             imap(d, \(v, k) flow(v, k, indent + 2)) |> unlist(use.names = FALSE))

pkg_block <- \(r) c(paste0("  ", r$pkg, ":"),
                    paste0("    core: ", tolower(r$core)),
                    flow(r$direct[[1]], "direct", 4),
                    flow(r$recursive[[1]], "recursive", 4),
                    flow(r$beyond_dplyr[[1]], "beyond_dplyr", 4))

lines <- c(
  "# Generated by gen-tidyverse-deps.R, do not edit by hand.",
  "# dep = Depends + Imports + LinkingTo; base + recommended R packages excluded.",
  "# Every list has a '# n = <count>' comment.",
  "meta:",
  paste0("  generated: ", Sys.Date()),
  paste0("  r_version: ", getRversion()),
  paste0("  tidyverse_version: ", packageVersion("tidyverse")),
  "",
  "# attached by library(tidyverse)",
  flow(core, "core", 0),
  "",
  "# installed on purpose by install.packages('tidyverse') (its Imports), minus the core",
  flow(setdiff(members, core), "non_core_members", 0),
  "",
  "# everything install.packages('tidyverse') ends up with",
  flow(all_deps, "all_deps", 0),
  "# ...of which only there as somebody's dependency, not on purpose",
  flow(setdiff(all_deps, members), "transitive_only", 0),
  "",
  "# who directly depends on whom, restricted to the core (A: [what A directly depends on])",
  edges(set_names(tv$uses_core, tv$pkg)[core], "core_graph", 0),
  "",
  "# ...and across all members (core + non-core)",
  edges(set_names(tv$uses_members, tv$pkg), "member_graph", 0),
  "",
  "# per member: direct deps, full recursive deps, and the recursive deps",
  "# that dplyr (and dplyr's own deps) doesn't already bring in",
  "packages:",
  tv |> group_split(pkg) |> map(\(g) c(pkg_block(g), "")) |> unlist()
)

writeLines(head(lines, -1), out)

# check: the file parses back to the same lists --------------------------------
back <- yaml::read_yaml(out)
stopifnot(
  identical(unlist(back$core), core),
  identical(unlist(back$all_deps), all_deps),
  identical(map(back$packages, \(p) as.character(unlist(p$recursive))), set_names(tv$recursive, tv$pkg)[names(back$packages)])
)
message("wrote ", out, " (", length(lines), " lines)")
